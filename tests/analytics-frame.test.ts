import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const code=fs.readFileSync(new URL('../dist/assets/analytics-frame.js',import.meta.url),'utf8');
test('Google loads only after a trusted consent message and receives canonical pages without personal fields',()=>{
 const scripts:Array<Record<string,unknown>>=[];const replies:unknown[]=[];
 const callbacks:Array<(event:Record<string,unknown>)=>void>=[];
 const parent={postMessage(message:unknown){replies.push(message);}};
 const window={parent,macAnalyticsConfig:{enabled:true,measurementId:'G-TEST12345',productionHosts:['mactecnologia.com.mx']},macAnalyticsLayer:[] as unknown[],addEventListener(_name:string,callback:typeof callbacks[number]){callbacks.push(callback);}};
 const location={origin:'https://mactecnologia.com.mx',hostname:'mactecnologia.com.mx',protocol:'https:',href:'https://mactecnologia.com.mx/analytics.html?email=private@example.test'};
 vm.runInNewContext(code,{window,location,URL,URLSearchParams,document:{createElement(){return {};},head:{append(script:Record<string,unknown>){scripts.push(script);}}}});
 const dispatch=(data:unknown,source:unknown=parent,origin=location.origin)=>callbacks[0]({data,source,origin});
 assert.equal(scripts.length,0);
 dispatch({type:'mac-analytics-start'},{},location.origin);dispatch({type:'mac-analytics-start'},parent,'https://evil.example');
 assert.equal(scripts.length,0);
 dispatch({type:'mac-analytics-start'});dispatch({type:'mac-analytics-start'});assert.equal(scripts.length,1);
 assert.equal(scripts[0].referrerPolicy,'no-referrer');
 (scripts[0].onload as ()=>void)();assert.equal(replies.length,1);
 dispatch({type:'mac-analytics-event',event:{name:'page_view',parameters:{language:'en',email:'private@example.test',page_location:'https://evil.example/?secret=private'}}});
 dispatch({type:'mac-analytics-event',event:{name:'form_submit',parameters:{language:'en'}}});
 const commands=window.macAnalyticsLayer.map(value=>Array.from(value as ArrayLike<unknown>));
 const events=commands.filter(command=>command[0]==='event');assert.equal(events.length,1);
 const parameters=events[0][2] as Record<string,unknown>;
 assert.equal(parameters.page_location,'https://mactecnologia.com.mx/en/');assert.equal(parameters.page_referrer,'');
 assert.doesNotMatch(JSON.stringify(commands),/private@example|secret=private|evil\.example/);
 const consent=commands.find(command=>command[0]==='consent'&&command[1]==='default')![2] as Record<string,unknown>;
 assert.equal(consent.analytics_storage,'denied');assert.equal(consent.ad_storage,'denied');assert.equal(consent.ad_user_data,'denied');assert.equal(consent.ad_personalization,'denied');
 const update=commands.find(command=>command[0]==='consent'&&command[1]==='update')![2] as Record<string,unknown>;
 assert.equal(update.analytics_storage,'granted');assert.equal(update.ad_storage,undefined);
 for(const command of commands.filter(value=>value[0]==='config'))assert.equal((command[2] as Record<string,unknown>).send_page_view,false);
});
